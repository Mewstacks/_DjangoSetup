"""Render the files AI coding agents read, from the rulebook in ``conventions.py``.

``AGENTS.md`` is the canonical one (the open convention read by Claude Code, Codex, Cursor,
Copilot, Gemini CLI, Windsurf and others). ``CLAUDE.md`` imports it, the Cursor rule and the
Copilot instructions repeat it, ``llms.txt`` indexes the documentation for models that read the
web, and ``docs/reference/conventions.json`` is the same knowledge for programs.

Everything here is a pure function of the code: ``scripts/gen_docs.py`` writes the files and
``--check`` (run by CI and by ``verify.py``) fails when one drifted.
"""

from __future__ import annotations

import json
import re
from pathlib import Path
from typing import Any

from devtools import conventions

ROOT = Path(__file__).resolve().parents[2]
GENERATED = (
    "<!-- Generated by scripts/gen_docs.py from src/devtools/conventions.py. "
    "Edit the source, not this file. -->"
)


def _bullets(items: tuple[str, ...]) -> str:
    return "\n".join(f"- {item}" for item in items)


def agents_body() -> str:
    p = conventions.PROJECT
    commands = "\n".join(f"- {what}: `{run}`" for what, run in conventions.COMMANDS)
    files = "\n".join(
        f"| `{name}` | {becomes} | {by if by != '-' else ''} |"
        for name, becomes, by in conventions.CONVENTION_FILES
    )
    rules = "\n\n".join(
        f"### {number}. `{rule.id}`\n{rule.rule}\n\n- Why: {rule.why}\n"
        f"- Enforced by: {rule.enforced_by}"
        for number, rule in enumerate(conventions.RULES, 1)
    )
    lgpd = "\n".join(
        f"{number}. **{question}** {answer}"
        for number, (question, answer) in enumerate(conventions.LGPD_DECISIONS, 1)
    )
    where = "\n".join(f"- {topic}: {path}" for topic, path in conventions.WHERE_TO_LOOK)
    return f"""## What this is

{p["summary"]}

Stack: {p["stack"]}.

## Commands

{commands}

Run `python scripts/verify.py --fast` before you say a change is done, and the full
`python scripts/verify.py` before you stop. Nothing is finished while the gate is red.

## Where things live

Each app is a folder under `src/apps/<app>/`. The platform finds these files **by name**; a file
with the right name in a registered app takes effect with no wiring.

| File | What it is | Discovered by |
|---|---|---|
{files}

Add an app to `LOCAL_APPS` in `src/config/settings/base.py`. Prefer
`python manage.py scaffold resource <app> <Model> --fields ...` over writing the files by hand:
it produces all of the above, already following the rules below.

## Rules

Each rule says what is enforced and by what. If a test fails because of a rule, fix the code,
not the test.

{rules}

## Personal data (LGPD) decision tree

Answer these for every new model, in order:

{lgpd}

None of this is legal advice. Items about the ANPD, children and international transfer need a
lawyer's confirmation before launch.

## Definition of done

{_bullets(conventions.DEFINITION_OF_DONE)}

## Never

{_bullets(conventions.FORBIDDEN)}

## Where to look

{where}

## Tooling for agents

`python -m devtools.mcp` starts a Model Context Protocol server (stdio) with tools to describe
the project, explain an action, scaffold a resource, check these conventions, answer the LGPD
question for a model, run the gate and search the docs. `.mcp.json` registers it for clients
that read that file. It writes only under `src/` and `tests/`, and only when asked to.
"""


def agents_md() -> str:
    return f"# AGENTS.md\n\n{GENERATED}\n\n{agents_body()}"


def claude_md() -> str:
    return (
        f"{GENERATED}\n\n@AGENTS.md\n\n"
        "Claude Code: the rules above are enforced by tests; run `python scripts/verify.py --fast`\n"
        "after every change and use the `devmcp` server's `check_conventions` before you finish.\n"
    )


def cursor_rule() -> str:
    return (
        "---\n"
        "description: Rules for building on this multi-tenant, LGPD-aware Django platform\n"
        "alwaysApply: true\n"
        "---\n\n"
        f"{GENERATED}\n\n{agents_body()}"
    )


def copilot_instructions() -> str:
    return f"{GENERATED}\n\n# Copilot instructions\n\n{agents_body()}"


# --- llms.txt ---------------------------------------------------------------------------------


def _is_prose(line: str) -> bool:
    """A sentence, not a table row, a code line or a diagram."""
    if not line or line.startswith(("#", ">", "|", "`", "-", "*", "<", "1.")):
        return False
    if re.search(r"[─│┐└┘├┤┬┴┼►▶]|^(from|import|python|uv|curl|pip)\b|[{};]", line):
        return False
    return len(line.split()) >= 6 and line[0].isupper()


def _title_and_lead(path: Path) -> tuple[str, str]:
    """The page's first heading and its first plain sentence (tables, quotes, code skipped)."""
    title, lead = "", ""
    for line in path.read_text(encoding="utf-8").splitlines():
        stripped = line.strip()
        if not title and stripped.startswith("# "):
            title = stripped[2:].strip()
        elif title and not lead and _is_prose(stripped):
            plain = re.sub(r"\[([^\]]+)\]\([^)]*\)", r"\1", stripped)  # links keep their text
            lead = re.sub(r"\s+", " ", plain)[:160]
        if title and lead:
            break
    return title or path.stem.replace("-", " ").title(), lead


def _doc_sections() -> list[tuple[str, list[Path]]]:
    base = ROOT / "docs" / "en"
    order = ("guides", "reference", "security", "lgpd", "deploy", "migration", "adr")
    sections: list[tuple[str, list[Path]]] = [
        (
            "Start here",
            [
                p
                for p in (base / "index.md", base / "quickstart.md", base / "architecture.md")
                if p.exists()
            ],
        )
    ]
    for folder in order:
        files = sorted((base / folder).glob("*.md")) if (base / folder).exists() else []
        if files:
            sections.append((folder.replace("-", " ").title(), files))
    return sections


def llms_txt() -> str:
    lines = [
        f"# {conventions.PROJECT['name']}",
        "",
        f"> {conventions.PROJECT['summary']}",
        "",
        "Read AGENTS.md first: it holds the rules, the commands and the definition of done. "
        "The links below are repository paths.",
        "",
        "## Agents",
        "",
        "- [AGENTS.md](AGENTS.md): rules, commands, LGPD decision tree, definition of done",
        "- [docs/reference/conventions.json](docs/reference/conventions.json): the same, as data",
        "- [docs/reference/actions.json](docs/reference/actions.json): every action, scope and schema",
        "",
    ]
    for heading, files in _doc_sections():
        lines += [f"## {heading}", ""]
        for path in files:
            title, lead = _title_and_lead(path)
            relative = path.relative_to(ROOT).as_posix()
            lines.append(f"- [{title}]({relative})" + (f": {lead}" if lead else ""))
        lines.append("")
    lines += [
        "## Optional",
        "",
        "- [Portuguese documentation](docs/pt-BR/index.md): the same pages in Brazilian Portuguese",
        "",
    ]
    return "\n".join(lines)


def llms_full_txt() -> str:
    parts = [llms_txt(), "\n---\n", f"# AGENTS.md\n\n{agents_body()}"]
    for _, files in _doc_sections():
        for path in files:
            parts.append(f"\n---\n\n<!-- {path.relative_to(ROOT).as_posix()} -->\n")
            parts.append(path.read_text(encoding="utf-8").strip() + "\n")
    return "\n".join(parts)


# --- conventions.json ---------------------------------------------------------------------------


def conventions_json() -> str:
    """The rulebook plus what is registered right now (needs Django to be set up)."""
    from apps.actions.registry import REGISTRY, known_scopes
    from apps.flags.registry import SETTINGS
    from apps.flows.declare import FLOWS, JOBS
    from apps.privacy.catalog import CATALOG
    from apps.webhooks.events import EVENT_TYPES

    data: dict[str, Any] = {
        "project": conventions.PROJECT,
        "commands": [{"what": what, "run": run} for what, run in conventions.COMMANDS],
        "convention_files": [
            {"file": f, "becomes": becomes, "discovered_by": by}
            for f, becomes, by in conventions.CONVENTION_FILES
        ],
        "rules": [
            {"id": r.id, "rule": r.rule, "why": r.why, "enforced_by": r.enforced_by}
            for r in conventions.RULES
        ],
        "definition_of_done": list(conventions.DEFINITION_OF_DONE),
        "forbidden": list(conventions.FORBIDDEN),
        "lgpd_decisions": [{"question": q, "answer": a} for q, a in conventions.LGPD_DECISIONS],
        "registered": {
            "actions": sorted(REGISTRY),
            "scopes": sorted(known_scopes()),
            "webhook_events": sorted(EVENT_TYPES),
            "flows": sorted(FLOWS),
            "jobs": {name: spec.schedule for name, spec in sorted(JOBS.items())},
            "settings": sorted(SETTINGS),
            "personal_models": sorted(k for k, v in CATALOG.items() if v.personal),
            "not_personal_models": sorted(k for k, v in CATALOG.items() if not v.personal),
        },
    }
    return json.dumps(data, indent=2, sort_keys=True, ensure_ascii=False) + "\n"


def render_all() -> dict[str, str]:
    """Every generated agent-facing file, keyed by repository path."""
    return {
        "AGENTS.md": agents_md(),
        "CLAUDE.md": claude_md(),
        ".cursor/rules/saas-base.mdc": cursor_rule(),
        ".github/copilot-instructions.md": copilot_instructions(),
        "llms.txt": llms_txt(),
        "llms-full.txt": llms_full_txt(),
        "docs/reference/conventions.json": conventions_json(),
    }
