def register_app(settings_path: Path, app: str) -> bool:
    """Add ``apps.<app>`` to LOCAL_APPS. False when the list could not be found."""
    text = settings_path.read_text(encoding="utf-8")
    entry = f'    "apps.{app}",'
    if entry in text:
        return True
    match = re.search(r"LOCAL_APPS = \[\n(.*?)\n\]", text, re.DOTALL)
    if match is None:
        return False
    start, end = match.span(1)
    settings_path.write_text(text[:end] + "\n" + entry + text[end:], encoding="utf-8", newline="\n")
    del start
    return True


def format_files(root: Path, names: list[str]) -> bool:
    """Run the project's own formatter and import sorter over what was written.

    The generated code is close to the house style but not byte-identical to ``ruff format``,
    and ``scripts/verify.py`` fails on a file that would be reformatted: a scaffold that leaves
    the gate red is not helping. Returns False when ruff is not installed.
    """
    paths = [name for name in names if name.endswith(".py")]
    for command in (
        ["check", "--fix", "--select", "I,UP", "--quiet"],
        ["format", "--quiet"],
    ):
        done = subprocess.run(  # noqa: S603
            [sys.executable, "-m", "ruff", *command, *paths],
            cwd=root,
            capture_output=True,
            text=True,
            check=False,
        )
        if "No module named" in done.stderr:
            return False
    return True


def write(
    root: Path,
    files: dict[str, str],
    *,
    register: bool = True,
    app: str = "",
    format_code: bool = True,
) -> list[str]:
    """Write ``files`` under ``root``; refuse to overwrite anything."""
    existing = [name for name in files if (root / name).exists() and files[name] != ""]
    if existing:
        raise ScaffoldError(f"Refusing to overwrite: {', '.join(existing)}")
    written: list[str] = []
    for name, content in files.items():
        target = root / name
        target.parent.mkdir(parents=True, exist_ok=True)
        if not target.exists():
            target.write_text(content, encoding="utf-8", newline="\n")
            written.append(name)
    if register and app:
        settings_path = root / "src/config/settings/base.py"
        if settings_path.exists():
            register_app(settings_path, app)
    if format_code and written:
        format_files(root, written)
    return written
