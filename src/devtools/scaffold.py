def render(app: str, model: str, fields: list[Field]) -> dict[str, str]:
    if not NAME.fullmatch(app) or keyword.iskeyword(app):
        raise ScaffoldError(f"App name {app!r} must be snake_case (a plural noun: invoices).")
    if app in RESERVED_APPS:
        raise ScaffoldError(f"{app!r} is taken by the platform; choose another name.")
    if not MODEL.fullmatch(model):
        raise ScaffoldError(f"Model name {model!r} must be CamelCase (Invoice).")
    return {
        f"src/apps/{app}/__init__.py": "",
        f"src/apps/{app}/apps.py": (
            "from django.apps import AppConfig\n\n\n"
            f"class {model}sConfig(AppConfig):\n"
            '    default_auto_field = "django.db.models.BigAutoField"\n'
            f'    name = "apps.{app}"\n'
        ),
        f"src/apps/{app}/models.py": _models(app, model, fields),
        f"src/apps/{app}/services.py": _services(app, model, fields),
        f"src/apps/{app}/actions.py": _actions(app, model, fields),
        f"src/apps/{app}/undo.py": _undo(app, model, fields),
        f"src/apps/{app}/events.py": _events(app, model),
        f"src/apps/{app}/agent.py": _agent(app, model, fields),
        f"src/apps/{app}/privacy.py": _privacy(app, model, fields),
        f"src/apps/{app}/migrations/__init__.py": "",
        f"tests/test_{app}.py": _tests(app, model, fields),
    }


