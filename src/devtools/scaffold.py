"""Generate a tenant resource that already follows the platform's rules.

``render`` is pure: it returns ``{relative path: source}`` and touches nothing, so a person, a
test or an AI agent can look at the plan first. ``write`` applies it, refusing to overwrite.

What comes out is a small Django app with the model, the service, five actions (list, get,
create, update, archive), the undo handlers, the webhook events, the MCP resource and prompt, the
LGPD catalog entry and a test file. It is a starting point to *review*, not a finished feature:
the privacy entry in particular is generated with the safest defaults and a list of decisions
that only the product owner can make.
"""

from __future__ import annotations

import keyword
import re
import subprocess
import sys
from dataclasses import dataclass
from pathlib import Path

NAME = re.compile(r"^[a-z][a-z0-9_]{1,30}$")
MODEL = re.compile(r"^[A-Z][A-Za-z0-9]{1,40}$")
RESERVED_APPS = {
    "actions", "accounts", "apikeys", "audit", "common", "examples", "flags", "flows",
    "observability", "oauth", "organizations", "privacy", "uploads", "webhooks", "devtools",
    "config", "tests", "django", "admin", "auth",
}  # fmt: skip


class ScaffoldError(ValueError):
    pass


@dataclass(frozen=True, slots=True)
class Kind:
    django: str  # the model field expression
    python: str  # the pydantic type in the *Out model
    input_python: str  # the pydantic type in the *In models
    category: str  # LGPD category of the field
    anonymized: str  # replacement value in the on_erase rule (a Python expression)
    sample: str  # a valid value in the generated test (a Python expression)


KINDS: dict[str, Kind] = {
    "str": Kind(
        "models.CharField(max_length=200)",
        "str",
        "str = Field(min_length=1, max_length=200)",
        "CONTENT",
        '"[removed]"',
        '"sample"',
    ),
    "text": Kind(
        "EncryptedTextField(blank=True)",
        "str",
        'str = Field("", max_length=20_000)',
        "CONTENT",
        '""',
        '"sample text"',
    ),
    "int": Kind("models.IntegerField(default=0)", "int", "int = 0", "BEHAVIOR", "0", "3"),
    "bool": Kind(
        "models.BooleanField(default=False)", "bool", "bool = False", "BEHAVIOR", "False", "True"
    ),
    "decimal": Kind(
        "models.DecimalField(max_digits=12, decimal_places=2, default=0)",
        "Decimal",
        "Decimal = Decimal(0)",
        "FINANCIAL",
        "0",
        "Decimal('10.50')",
    ),
    "datetime": Kind(
        "models.DateTimeField(null=True, blank=True)",
        "datetime | None",
        "datetime | None = None",
        "BEHAVIOR",
        "None",
        "None",
    ),
}  # fmt: skip


@dataclass(frozen=True, slots=True)
class Field:
    name: str
    kind: str

    @property
    def spec(self) -> Kind:
        return KINDS[self.kind]


def parse_fields(raw: str) -> list[Field]:
    """``"title:str,body:text"`` -> fields. The first ``str`` field names the record."""
    fields: list[Field] = []
    for part in [p.strip() for p in raw.split(",") if p.strip()]:
        name, _, kind = part.partition(":")
        name, kind = name.strip(), (kind.strip() or "str")
        if not NAME.fullmatch(name) or keyword.iskeyword(name):
            raise ScaffoldError(f"Field name {name!r} must be snake_case and not a keyword.")
        if name in {"id", "organization", "created_at", "updated_at", "archived_at", "created_by"}:
            raise ScaffoldError(f"{name!r} already exists on every resource.")
        if kind not in KINDS:
            raise ScaffoldError(f"Field {name!r}: type {kind!r} is not one of {sorted(KINDS)}.")
        if any(f.name == name for f in fields):
            raise ScaffoldError(f"Field {name!r} is declared twice.")
        fields.append(Field(name, kind))
    if not fields:
        raise ScaffoldError("Give at least one field, for example --fields 'title:str'.")
    return fields


def _snake(model: str) -> str:
    return re.sub(r"(?<!^)(?=[A-Z])", "_", model).lower()


def _labelled(fields: list[Field]) -> Field:
    return next((f for f in fields if f.kind == "str"), fields[0])


